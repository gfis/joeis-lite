#:# Usage:
#:#     perl recperiod.pl [-d mode] [-f sigperiod_file] input.seq4 > output.seq4
#:#         -d mode 0=none, 1=some, 2= most
#:#         -f file with special period-generating signatures and period lengths
#--------------------------------------------------------
use strict;
use integer;
use warnings;
my ($sec, $min, $hour, $mday, $mon, $year, $wday, $yday, $isdst) = localtime (time);
my $timestamp = sprintf ("%04d-%02d-%02d %02d:%02d", $year + 1900, $mon + 1, $mday, $hour, $min);

my $debug = 0;
my $sigperiod_file = "sigperiod3.tmp";
while (scalar(@ARGV) > 0 and ($ARGV[0] =~ m{\A[\-\+]})) {
    my $opt = shift(@ARGV);
    if (0) {
    } elsif ($opt  =~ m{d}) {
        $debug     = shift(@ARGV);
    } elsif ($opt  =~ m{f}) {
        $sigperiod_file = shift(@ARGV);
    } else {
        die "invalid option \"$opt\"\n";
    }
} # while $opt

my ($aseqno, $callcode, $offset1, $matrix, $inits, $perlen, @rest);
my %hash;
open(SIG, "<", $sigperiod_file) || die "canot read \"$sigperiod_file\"\n";
my $count = 0;
while (<SIG>) {
    s/\s+\Z//; # chompr
    ($aseqno, $callcode, $offset1, $matrix, $inits, $perlen, @rest) = split(/\s+/);
    $hash{$matrix} = $perlen;
    print STDERR "# special $matrix length $perlen\n" if $debug >= 2;
    $count ++;
} # while <SIG>
close(SIG);
print STDERR "# $count special signatures read\n";

print "# Generated by $0.pl V1.1 at $timestamp\n";
while (<>) {
# while (<DATA>) {
    next if !m{\AA};
    s/\s+\Z//; # chompr
    my $line = $_;
    my $nok = "ack";
    ($aseqno, $callcode, $offset1, $matrix, $inits, $perlen, @rest) = split(/\t/, $line);
    if (0) {
    #                               12   2 1
    } elsif ($matrix =~ m{\A\[0\,1\,((0\,)+)\-1\]}) { 
        my $temp = $1 . "0";
        $perlen = scalar(split(/\,/, $temp));
    } elsif (defined($hash{$matrix})) {
        $perlen = $hash{$matrix};
    } else {
        $nok = "nak";
    }
    if ($nok eq "ack") {
        $inits =~ s{[\[\]]}{}g; # remove brackets
        my @terms = split(/\,/, $inits);
        my $terlen = scalar(@terms);
        my $oldcode = $rest[1];
        if ($perlen == $terlen) { # pure periodic
            $callcode = "periodic";
            print join("\t", $aseqno, $callcode, $offset1, "[]", "[$inits]", 0, $terlen, $oldcode) . "\n";
        } else {
            $callcode = "padding";
            my @prefix = splice(@terms, 0, $terlen - $perlen); # @terms now has $perlen elements
            $matrix = "[" . join(",", @prefix) . "]";
            my $premod = scalar(@prefix) % $perlen; # so many of the period are occupied by the prefix
            my @preper = splice(@terms, 0, $perlen - $premod);
            push(@terms, @preper);
            $inits  = "[" . join(",", @terms ) . "]";
            print join("\t", $aseqno, $callcode, $offset1, $matrix, $inits, scalar(@prefix), scalar(@terms), $oldcode) . "\n"; # , $perlen, $terlen, $temp) . "\n";
        }
    }
} # while <> 
