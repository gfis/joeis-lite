use strict;
use integer;
use warnings;
my ($sec, $min, $hour, $mday, $mon, $year, $wday, $yday, $isdst) = localtime (time);
my $timestamp = sprintf ("%04d-%02d-%02d %02d:%02d", $year + 1900, $mon + 1, $mday, $hour, $min);

my $debug = 0;
while (scalar(@ARGV) > 0 and ($ARGV[0] =~ m{\A[\-\+]})) {
    my $opt = shift(@ARGV);
    if (0) {
    } elsif ($opt  =~ m{d}) {
        $debug     = shift(@ARGV);
    } else {
        die "invalid option \"$opt\"\n";
    }
} # while $opt

# print "# Generated by $0 V1.1 at $timestamp\n";
my $old_matrix = "";
my $matrix;
while (<>) {
# while (<DATA>) {
    s/\s+\Z//; # chompr
    next if !m{\AA\d+\t};
    my $line = $_;
    my ($aseqno, $callcode, $offset1, $matstr, $inistr, $perlen, $square, $sort, @rest) = split(/\t/, $line);
    $inistr    =~ s{[\[\] ]}{}g;
    my @inits  = split(/\,/, $inistr);
    my $inilen = scalar(@inits);
    if ($callcode =~ m{num}) {
        $matrix = "[-1," . ("0," x ($perlen - 1)) . (2 * $inits[$perlen - 1]) . (",0" x ($perlen - 1)) . ",-1]";
    } else {
        $matrix = $old_matrix;
    }
    print join("\t", $aseqno, "linearec", $offset1, $matrix, "[$inistr]", $perlen, $sort) . "\n"; 
    $old_matrix = $matrix;
} # while <>
