#!perl

# special signatures generating periodic sequences, not from (1-x^k)
# @(#) $Id$
# 2026-11-05, Georg Fischer; *KR=83
#
#:# Usage:
#:#     # download lrindx.raw from https://oeis.org/wiki/Index_to_OEIS:_Section_Rec
#:#     perl sigperiod.pl [-a add] [-d mode] lrindex/lrindx.raw > output.seq4
#:#         -d mode 0=none, 1=some, 2= most
#:#         -a additional terms (default 0)
#--------------------------------------------------------
use strict;
use integer;
use warnings;
my ($sec, $min, $hour, $mday, $mon, $year, $wday, $yday, $isdst) = localtime (time);
my $timestamp = sprintf ("%04d-%02d-%02d %02d:%02d", $year + 1900, $mon + 1, $mday, $hour, $min);

my $add   = 0;
my $debug = 0;
while (scalar(@ARGV) > 0 and ($ARGV[0] =~ m{\A[\-\+]})) {
    my $opt = shift(@ARGV);
    if (0) {
    } elsif ($opt  =~ m{a}) {
        $add       = shift(@ARGV);
    } elsif ($opt  =~ m{d}) {
        $debug     = shift(@ARGV);
    } else {
        die "invalid option \"$opt\"\n";
    }
} # while $opt

print "# Generated by $0 V1.1 at $timestamp\n";
while (<>) {
# while (<DATA>) {
    s/\s+\Z//; # chompr
    my $line = $_;
    print "#1: $line\n" if $debug >= 1;
    next if $line =~ m{\.\.\.|^\:\(\)\,|differences are|(\d\d\d|\D[7-9]\d|\D6[5-9])\-periodic}; # no ellipsis, differences, or longer than 64
    print "#2: $line\n" if $debug >= 1;
    next if $line =~ m{\A\:\((0\,)+1\)}; # ordinary (1-x^k)
    print "#3: $line\n" if $debug >= 1;
    #                   (1      2        2 1 )
    if ($line =~ m{\A\:\((\-?\d+(\,\-?\d+)*)\)}) {
        my @signat = (0, reverse(split(/\, */, $1)), -1); # reversed signature (holos convention, prefixed with constant=0)
        print "#4: $line\n" if $debug >= 1;
        #              1   1             2  2
        if ($line =~ m{(\d+)\-periodic[^\:]*\: (.*)}) {
            my $perlen = $1;
            my $arest  = $2;
            $arest =~ s{\s}{}g;
            my @anos = map {
                s{\A(A\d+).*}{$1};
                $_
                } split(/\,/, $arest);
            foreach my $aseqno (@anos) {
                print join("\t", $aseqno, "sigperiod", 0, "[" . join("\,", @signat) . "]", $perlen + $add, $perlen, $perlen + $add) . "\n";
            } # foreach
        }
    }
} # while <>
