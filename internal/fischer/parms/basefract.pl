use strict;
use integer;
use warnings;
my ($sec, $min, $hour, $mday, $mon, $year, $wday, $yday, $isdst) = localtime (time);
my $timestamp = sprintf ("%04d-%02d-%02d %02d:%02d", $year + 1900, $mon + 1, $mday, $hour, $min);

my $add   = 0;
my $debug = 0;
while (scalar(@ARGV) > 0 and ($ARGV[0] =~ m{\A[\-\+]})) {
    my $opt = shift(@ARGV);
    if (0) {
    } elsif ($opt  =~ m{a}) {
        $add       = shift(@ARGV);
    } elsif ($opt  =~ m{d}) {
        $debug     = shift(@ARGV);
    } else {
        die "invalid option \"$opt\"\n";
    }
} # while $opt

print "# Generated by $0 V1.2 at $timestamp\n"; 
my %hash = qw(
    decimal 10
    binary   2
    ternary  3
    );
while (<>) {
# while (<DATA>) {
    s/\s+\Z//; # chompr
    my $line = substr($_, 3);
    #                   (1      2        2 1 )
    if ($line =~ m{\A[A-Z](\d+) }) {
        my $aseqno = "A$1";
        #              1   1               2      2      3   3
        if ($line =~ m{(\w+) expansion of +(\-?\d+) *\/ *(\d+)\.}i) {
            my ($word, $num, $den) = (lc($1), $2, $3);
            my $base = $hash{$word};
            if (defined($base)) { 
                print join("\t", $aseqno, "basefract", 0, $num, $den, $base) . "\n";
            } else {
                print STDERR "$line\n";
            }
        } else {
            # ignore
        }
    }
} # while <>
